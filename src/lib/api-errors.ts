/** Global error handler converting uncaught exceptions to RFC 7807 responses. */
export function handleApiProblemError(
  err: unknown,
  instance?: string
): NextResponse {
  if (err instanceof z.ZodError) {
    return validationProblemDetails(err, instance);
  }

  const message = err instanceof Error ? err.message : String(err);
  return formatProblemDetails({
    type: "https://api.ophirpay.com/errors/internal-server-error",
    title: "Internal Server Error",
    status: 500,
    detail: process.env.NODE_ENV === "production" ? "An unexpected error occurred" : message,
    code: ERROR_CODES.INTERNAL_ERROR,
    instance,
  });
}
