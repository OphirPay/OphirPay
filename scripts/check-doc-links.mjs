/**
 * Generate GitHub-compatible slugs for heading text.
 * Returns an array of valid slug variants (including Unicode letters/accents,
 * emoji stripping, multi-dash retention, and normalized variants).
 */
export function getHeadingSlugs(heading) {
  const slugs = new Set();

  // Strip HTML tags and lowercase
  const clean = heading.replace(/<[^>]+>/g, "").toLowerCase();

  // Keep letters (\p{L}), marks/accents (\p{M}), numbers (\p{N}), connector punctuation (\p{Pc}), hyphens (-), and spaces
  const stripped = clean.replace(/[^\p{L}\p{M}\p{N}\p{Pc}\- ]/gu, "");

  // Standard GitHub slug (spaces replaced with dashes)
  const ghSlug = stripped.replace(/ /g, "-");
  if (ghSlug) slugs.add(ghSlug);

  // Without Unicode variation selectors (e.g. \uFE0F)
  const noVs = ghSlug.replace(/[\uFE00-\uFE0F]/gu, "");
  if (noVs) slugs.add(noVs);

  // Without leading dashes (for headings where stripped emoji left a leading space)
  if (ghSlug) slugs.add(ghSlug.replace(/^-+/, ""));
  if (noVs) slugs.add(noVs.replace(/^-+/, ""));

  // Without trailing dashes (for headings where stripped punctuation left a trailing space)
  if (ghSlug) {
    slugs.add(ghSlug.replace(/-+$/, ""));
    slugs.add(ghSlug.replace(/^-+/, "").replace(/-+$/, ""));
  }
  if (noVs) {
    slugs.add(noVs.replace(/-+$/, ""));
    slugs.add(noVs.replace(/^-+/, "").replace(/-+$/, ""));
  }

  // With collapsed multiple dashes
  if (ghSlug) slugs.add(ghSlug.replace(/-+/g, "-"));
  if (noVs) slugs.add(noVs.replace(/-+/g, "-"));
  if (ghSlug) slugs.add(ghSlug.replace(/^-+|-+$/g, "").replace(/-+/g, "-"));
  if (noVs) slugs.add(noVs.replace(/^-+|-+$/g, "").replace(/-+/g, "-"));

  // Slug generated by trimming before space conversion
  const trimmedSlug = stripped.trim().replace(/ /g, "-");
  if (trimmedSlug) slugs.add(trimmedSlug);
  if (trimmedSlug) slugs.add(trimmedSlug.replace(/-+/g, "-"));

  return Array.from(slugs).filter(Boolean);
}

/**
 * Recursively find all markdown files.
 */
function findMarkdownFiles(dir) {
  const files = [];
  const entries = fs.readdirSync(dir, { withFileTypes: true });

  for (const entry of entries) {
    if (EXCLUDED_DIRS.has(entry.name)) continue;
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...findMarkdownFiles(fullPath));
    } else if (entry.isFile() && entry.name.endsWith(".md")) {
      files.push(fullPath);
    }
  }
  return files;
}

/**
 * Extract all headings, custom anchor tags, and IDs from a markdown file.
 */
function extractAnchors(content) {
  const anchors = new Map(); // slug -> 1
  const headingOccurrences = new Map();
  const lines = content.split("\n");
  let inCodeBlock = false;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];

    if (line.trim().startsWith("```") || line.trim().startsWith("~~~")) {
      inCodeBlock = !inCodeBlock;
      continue;
    }
    if (inCodeBlock) continue;

    // Headings: # Heading
    const headingMatch = line.match(/^#{1,6}\s+(.+)$/);
    if (headingMatch) {
      let rawHeading = headingMatch[1].trim();
      // Remove trailing hashes if present
      rawHeading = rawHeading.replace(/\s+#+$/, "");
      const rawCount = headingOccurrences.get(rawHeading) || 0;
      headingOccurrences.set(rawHeading, rawCount + 1);

      const generatedSlugs = getHeadingSlugs(rawHeading);
      for (const slug of generatedSlugs) {
        anchors.set(slug, 1);
        if (rawCount > 0) {
          anchors.set(`${slug}-${rawCount}`, 1);
        }
      }
    }

    // HTML anchors: <a id="..."> or <a name="..."> or <span id="...">
    const htmlIdMatches = line.matchAll(/<(?:a|span|div)[^>]*(?:id|name)=["']([^"']+)["']/gi);
    for (const match of htmlIdMatches) {
      anchors.set(match[1].toLowerCase(), 1);
      anchors.set(match[1], 1);
    }
  }

  return anchors;
}

/**
 * Extract all links from a markdown document.
 * Returns array of { href, line, text }
 */
function extractLinks(content) {
  const links = [];
  const lines = content.split("\n");
  let inCodeBlock = false;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];

    if (line.trim().startsWith("```") || line.trim().startsWith("~~~")) {
      inCodeBlock = !inCodeBlock;
      continue;
    }
    if (inCodeBlock) continue;

    // Remove inline code snippets `...` before checking links to prevent matching code syntax
    const sanitizedLine = line.replace(/`[^`]+`/g, "");

    // Match Markdown links: [text](href) or ![alt](href)
    const linkRegex = /!?\[([^\]]*)\]\(([^)]+)\)/g;
    let match;
    while ((match = linkRegex.exec(sanitizedLine)) !== null) {
      let href = match[2].trim();
      // Split on title: [text](url "title")
      href = href.split(/\s+/)[0];
      links.push({
        href,
        text: match[1].trim(),
        line: i + 1,
      });
    }

    // Match HTML href: <a href="...">
    const htmlLinkRegex = /<a[^>]+href=["']([^"']+)["']/gi;
    while ((match = htmlLinkRegex.exec(sanitizedLine)) !== null) {
      links.push({
        href: match[1].trim(),
        text: "",
        line: i + 1,
      });
    }
  }

  return links;
}

export function runDocLinkChecker(options = {}) {
  const { checkExternal = false, baseDir = REPO_ROOT } = options;
  const files = findMarkdownFiles(baseDir);
  const fileAnchors = new Map();

  for (const file of files) {
    const content = fs.readFileSync(file, "utf8");
    fileAnchors.set(file, extractAnchors(content));
  }

  const internalErrors = [];
  const externalWarnings = [];

  for (const file of files) {
    const relFile = path.relative(REPO_ROOT, file);
    const content = fs.readFileSync(file, "utf8");
    const links = extractLinks(content);

    for (const { href, line } of links) {
      // Ignore mailto or tel
      if (href.startsWith("mailto:") || href.startsWith("tel:")) continue;

      // External URLs
      if (/^https?:\/\//i.test(href)) {
        try {
          const parsed = new URL(href);
          const isAllowlisted = ALLOWLISTED_HOSTS.some(
            (host) => parsed.hostname === host || parsed.hostname.endsWith(`.${host}`)
          );
          if (!isAllowlisted && checkExternal) {
            externalWarnings.push({
              file: relFile,
              line,
              href,
              message: `External host "${parsed.hostname}" not in allowlist`,
            });
          }
        } catch {
          externalWarnings.push({
            file: relFile,
            line,
            href,
            message: "Malformed external URL",
          });
        }
        continue;
      }

      // Same-file anchor: #heading
      if (href.startsWith("#")) {
        const anchor = href.slice(1).toLowerCase();
        // Skip empty anchor #
        if (!anchor) continue;

        const anchors = fileAnchors.get(file);
        if (!anchors || !anchors.has(anchor)) {
          internalErrors.push({
            file: relFile,
            line,
            href,
            message: `Missing anchor target "#${anchor}" in ${relFile}`,
          });
        }
        continue;
      }

      // Relative or absolute file link: path/to/file.md#anchor or /path/to/file
      const [filePathPart, anchorPart] = href.split("#");
      let resolvedTarget;

      if (filePathPart.startsWith("/")) {
        resolvedTarget = path.join(REPO_ROOT, filePathPart);
      } else {
        resolvedTarget = path.resolve(path.dirname(file), filePathPart);
      }

      // Check if file exists
      if (!fs.existsSync(resolvedTarget)) {
        internalErrors.push({
          file: relFile,
          line,
          href,
          message: `Target file does not exist: "${filePathPart}" (resolved to ${path.relative(REPO_ROOT, resolvedTarget)})`,
        });
        continue;
      }

      // If it has an anchor fragment and targets a markdown file
      if (anchorPart && resolvedTarget.endsWith(".md")) {
        let anchors = fileAnchors.get(resolvedTarget);
        if (!anchors) {
          anchors = extractAnchors(fs.readFileSync(resolvedTarget, "utf8"));
          fileAnchors.set(resolvedTarget, anchors);
        }
        const lowerAnchor = anchorPart.toLowerCase();
        if (!anchors.has(lowerAnchor)) {
          internalErrors.push({
            file: relFile,
            line,
            href,
            message: `Anchor "#${anchorPart}" not found in target file ${path.relative(REPO_ROOT, resolvedTarget)}`,
          });
        }
      }
    }
  }

  return {
    totalFiles: files.length,
    internalErrors,
    externalWarnings,
  };
}

// CLI entry point
if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(__filename)) {
  const checkExternal = process.argv.includes("--check-external");
  console.log("🔍 Scanning markdown documentation links and anchor fragments...");
  const result = runDocLinkChecker({ checkExternal });

  console.log(`\nChecked ${result.totalFiles} Markdown files.`);

  if (result.externalWarnings.length > 0) {
    console.warn(`\n⚠️  ${result.externalWarnings.length} external link warning(s):`);
    for (const w of result.externalWarnings) {
      console.warn(`  • ${w.file}:${w.line} -> ${w.href} (${w.message})`);
    }
  }

  if (result.internalErrors.length > 0) {
    console.error(`\n❌ Found ${result.internalErrors.length} broken internal link(s) / anchor(s):`);
    for (const err of result.internalErrors) {
      console.error(`  • ${err.file}:${err.line} -> "${err.href}": ${err.message}`);
    }
    process.exit(1);
  }

  console.log("✅ All internal links and anchor fragments are valid!");
  process.exit(0);
}
