/**
 * RFC 7807 Problem Details for HTTP APIs.
 *
 * Standardizes error responses across /api/payments routes so that client SDKs
 * and third-party consumers can parse errors consistently according to RFC 7807.
 * Error responses use the `application/problem+json` media type.
 *
 * @see https://www.rfc-editor.org/rfc/rfc7807
 */

import { z } from "zod";
import { getCurrentRequestId } from "@/lib/request-logging";
import { logger } from "@/lib/logger";
import { captureError } from "@/lib/sentry";

/** RFC 7807 Problem Details object shape. */
export interface ProblemDetails {
  /** A URI reference identifying the problem type. */
  type: string;
  /** A short, human-readable summary of the problem type. */
  title: string;
  /** The HTTP status code generated by the origin server for this occurrence. */
  status: number;
  /** A human-readable explanation specific to this occurrence of the problem. */
  detail?: string;
  /** A URI reference identifying the specific occurrence of the problem. */
  instance?: string;
  /** Machine-readable error code for backward compatibility with SDKs. */
  code?: string;
  /** Additional extension members, e.g. validation field errors. */
  errors?: Array<{ field: string; message: string }>;
  [key: string]: unknown;
}

export interface ProblemDetailsOptions {
  type?: string;
  title?: string;
  status: number;
  detail?: string;
  instance?: string;
  code?: string;
  errors?: Array<{ field: string; message: string }>;
  [key: string]: unknown;
}

/** Base URI for OphirPay problem types. */
export const PROBLEM_TYPE_BASE = "https://docs.ophirpay.com/errors";

/** Standard problem definitions mapped by HTTP status code. */
const STATUS_PROBLEMS: Record<number, { type: string; title: string }> = {
  400: { type: "bad-request", title: "Bad Request" },
  401: { type: "unauthorized", title: "Unauthorized" },
  403: { type: "forbidden", title: "Forbidden" },
  404: { type: "not-found", title: "Not Found" },
  409: { type: "conflict", title: "Conflict" },
  422: { type: "validation-error", title: "Validation Error" },
  429: { type: "rate-limited", title: "Too Many Requests" },
  500: { type: "internal-error", title: "Internal Server Error" },
  502: { type: "bad-gateway", title: "Bad Gateway" },
  503: { type: "service-unavailable", title: "Service Unavailable" },
};

/**
 * Format an RFC 7807 problem details object.
 *
 * Supports both options object:
 *   formatProblemDetails({ type, title, status, detail, instance, errors })
 * and positional parameters:
 *   formatProblemDetails(status, detail, extra)
 */
export function formatProblemDetails(
  arg1: number | ProblemDetailsOptions,
  arg2?: string,
  arg3?: Record<string, unknown>
): ProblemDetails {
  let opts: ProblemDetailsOptions;

  if (typeof arg1 === "object" && arg1 !== null) {
    opts = arg1;
  } else {
    opts = {
      status: arg1,
      detail: arg2,
      ...(arg3 ?? {}),
    };
  }

  const defaultMeta = STATUS_PROBLEMS[opts.status] ?? {
    type: "unknown-error",
    title: "An error occurred",
  };

  const type = opts.type ?? `${PROBLEM_TYPE_BASE}/${defaultMeta.type}`;
  const title = opts.title ?? defaultMeta.title;
  const requestId = getCurrentRequestId();
  const instance = opts.instance ?? (requestId ? `urn:request:${requestId}` : undefined);

  const derivedCode = opts.code ?? type.split("/").pop()?.toUpperCase()?.replace(/-/g, "_");

  const problem: ProblemDetails = {
    type,
    title,
    status: opts.status,
    ...(opts.detail ? { detail: opts.detail } : {}),
    ...(instance ? { instance } : {}),
    ...(derivedCode ? { code: derivedCode } : {}),
  };

  if (opts.errors) {
    problem.errors = opts.errors;
  }

  // Copy additional non-standard extension members
  for (const [key, val] of Object.entries(opts)) {
    if (
      key !== "type" &&
      key !== "title" &&
      key !== "status" &&
      key !== "detail" &&
      key !== "instance" &&
      key !== "errors" &&
      val !== undefined
    ) {
      problem[key] = val;
    }
  }

  return problem;
}

/**
 * Build an HTTP Response carrying `application/problem+json` content type.
 */
export function problemJsonResponse(
  problem: ProblemDetails,
  headers?: Record<string, string>
): Response {
  return new Response(JSON.stringify(problem), {
    status: problem.status,
    headers: {
      "Content-Type": "application/problem+json",
      ...(headers ?? {}),
    },
  });
}

/**
 * Convenience helper: format problem details and return an `application/problem+json` Response.
 */
export function problemResponse(
  statusOrOptions: number | ProblemDetailsOptions,
  detail?: string,
  extra?: Record<string, unknown>,
  headers?: Record<string, string>
): Response {
  const problem =
    typeof statusOrOptions === "number"
      ? formatProblemDetails(statusOrOptions, detail, extra)
      : formatProblemDetails(statusOrOptions);
  return problemJsonResponse(problem, headers);
}

/**
 * Map Zod validation issues into RFC 7807 field error structures.
 */
export function zodFieldErrors(err: z.ZodError): Array<{ field: string; message: string }> {
  return err.issues.map((issue) => ({
    field: issue.path.join("."),
    message: issue.message,
  }));
}

/**
 * Produce an RFC 7807 validation error response from a ZodError.
 */
export function zodValidationProblem(
  err: z.ZodError,
  status = 400,
  headers?: Record<string, string>
): Response {
  const problem = formatProblemDetails({
    type: `${PROBLEM_TYPE_BASE}/validation-error`,
    title: "Validation Error",
    status,
    detail: err.issues.map((e) => e.message).join("; ") || "Request validation failed",
    errors: zodFieldErrors(err),
  });
  return problemJsonResponse(problem, headers);
}

/**
 * Catch-all error handler for payments routes, returning RFC 7807 responses.
 */
export function handlePaymentProblemError(err: unknown, context?: string): Response {
  logger.error(context ?? "Payment API error", {
    requestId: getCurrentRequestId(),
    error: err instanceof Error ? err.message : String(err),
    stack: err instanceof Error ? err.stack : undefined,
  });

  if (process.env.NEXT_PUBLIC_SENTRY_DSN && !(err instanceof z.ZodError)) {
    captureError(err instanceof Error ? err : new Error(String(err)), {
      component: context ?? "PaymentsAPI",
    });
  }

  if (err instanceof z.ZodError) {
    return zodValidationProblem(err, 400);
  }

  const message = err instanceof Error ? err.message : "Internal server error";
  return problemResponse(500, message);
}
