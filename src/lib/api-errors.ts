/**
 * RFC 7807 (Problem Details for HTTP APIs) response formatting utilities (Issue #1364).
 *
 * Provides standardized error formatting across API mutation routes so client SDKs
 * and third-party consumers can parse error codes, messages, field validations,
 * and diagnostic instances uniformly with `Content-Type: application/problem+json`.
 */

import { NextResponse } from "next/server";
import { z } from "zod";
import { ERROR_CODES } from "@/lib/error-codes";

export const PROBLEM_JSON_MIME = "application/problem+json";

export interface ProblemDetailsOptions {
  /** A URI reference that identifies the problem type (RFC 7807 §3.1). */
  type?: string;
  /** A short, human-readable summary of the problem type (RFC 7807 §3.1). */
  title: string;
  /** The HTTP status code generated by the origin server (RFC 7807 §3.1). */
  status: number;
  /** A human-readable explanation specific to this occurrence (RFC 7807 §3.1). */
  detail?: string;
  /** A URI reference that identifies the specific occurrence of the problem (RFC 7807 §3.1). */
  instance?: string;
  /** Stable application error code for client SDKs. */
  code?: string;
  /** Field-level validation errors, if applicable. */
  errors?: Array<{ path?: string; field?: string; message: string }>;
  /** Additional custom problem extensions (RFC 7807 §3.2). */
  extensions?: Record<string, unknown>;
}

/**
 * Formats an RFC 7807 problem details response with `Content-Type: application/problem+json`.
 */
export function formatProblemDetails(options: ProblemDetailsOptions): NextResponse {
  const {
    type = "about:blank",
    title,
    status,
    detail,
    instance,
    code,
    errors,
    extensions = {},
  } = options;

  const payload: Record<string, unknown> = {
    type,
    title,
    status,
    ...(detail ? { detail } : {}),
    ...(instance ? { instance } : {}),
    ...(code ? { code } : {}),
    ...(errors && errors.length > 0 ? { errors } : {}),
    ...extensions,
  };

  return NextResponse.json(payload, {
    status,
    headers: {
      "Content-Type": PROBLEM_JSON_MIME,
    },
  });
}

/** Formats a Zod schema validation failure as an RFC 7807 400 Problem Details response. */
export function validationProblemDetails(
  err: z.ZodError,
  instance?: string
): NextResponse {
  const errors = err.issues.map((e) => ({
    field: e.path.join("."),
    path: e.path.join("."),
    message: e.message,
  }));

  return formatProblemDetails({
    type: "https://api.ophirpay.com/errors/validation-error",
    title: "Validation Error",
    status: 400,
    detail: "Request validation failed. One or more fields are invalid.",
    code: ERROR_CODES.VALIDATION_ERROR,
    instance,
    errors,
  });
}

/** Formats a 401 Unauthorized RFC 7807 Problem Details response. */
export function unauthorizedProblemDetails(
  message = "Authentication required. Connect your wallet or provide an API key.",
  instance?: string
): NextResponse {
  return formatProblemDetails({
    type: "https://api.ophirpay.com/errors/unauthorized",
    title: "Unauthorized",
    status: 401,
    detail: message,
    code: ERROR_CODES.UNAUTHORIZED,
    instance,
  });
}

